const ACADEMY = 'Open Mat Academy';

type ClassSeed = Omit<ScheduleClass, 'instructor'> & {
  instructor?: string;
};

function cls(seed: ClassSeed): ScheduleClass {
  return {
    instructor: seed.instructor ?? ACADEMY,
    ...seed,
  };
}

